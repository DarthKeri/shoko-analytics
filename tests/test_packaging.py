"""Release integrity and rollback checks; only synthetic temporary files."""
import argparse
import importlib.util
import json
import tempfile
import unittest
from zipfile import ZipFile
from pathlib import Path
from unittest.mock import patch

spec = importlib.util.spec_from_file_location('package_windows', Path(__file__).resolve().parent.parent / 'tools/package_windows.py')
package = importlib.util.module_from_spec(spec)
spec.loader.exec_module(package)


class PackagingTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name).resolve()
        self.candidate = self.root / 'build/candidate'
        self.candidate.mkdir(parents=True)
        self.files = ['ShokoAnalytics.exe', 'runtime/python.exe', 'runtime/pythonw.exe', 'runtime/python313.dll', 'app/main.py', 'app/shoko/__init__.py']
        for name in self.files:
            path = self.candidate / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(('synthetic ' + name).encode())
        self.manifest = {'version': '0.1.0', 'format': 'python-folder', 'files': {name: package.checksum(self.candidate / name) for name in self.files}}
        self.save_manifest()
        self.override = patch.object(package, 'ROOT', self.root)
        self.override.start()

    def tearDown(self):
        self.override.stop()
        self.temp.cleanup()

    def save_manifest(self):
        (self.candidate / 'build-manifest.json').write_text(json.dumps(self.manifest), encoding='utf-8')

    def test_verified_distribution_requires_all_recorded_files(self):
        self.assertEqual(package.verify(self.candidate)['version'], '0.1.0')
        (self.candidate / 'app/main.py').write_text('changed')
        with self.assertRaisesRegex(ValueError, 'Build file changed'):
            package.verify(self.candidate)

    def test_unlisted_source_is_rejected(self):
        (self.candidate / 'app/extra.py').write_text('unlisted')
        with self.assertRaisesRegex(ValueError, 'Unlisted'):
            package.verify(self.candidate)

    def test_missing_runtime_is_rejected_even_if_removed_from_manifest(self):
        del self.manifest['files']['runtime/python313.dll']
        (self.candidate / 'runtime/python313.dll').unlink()
        self.save_manifest()
        with self.assertRaisesRegex(ValueError, 'Required application files'):
            package.verify(self.candidate)

    def test_packaging_paths_cannot_escape_named_directory(self):
        with self.assertRaisesRegex(ValueError, 'must stay inside'):
            package.inside(self.root / 'build/../../outside', self.root / 'build')

    def test_failed_candidate_does_not_replace_existing_distribution(self):
        output = self.root / 'dist/ShokoAnalytics'
        output.mkdir(parents=True)
        (output / 'old.txt').write_text('previous')
        (self.candidate / 'app/main.py').write_text('changed')
        with self.assertRaises(ValueError):
            package.publish(argparse.Namespace(candidate=self.candidate))
        self.assertEqual((output / 'old.txt').read_text(), 'previous')

    def test_failed_rename_restores_previous_distribution(self):
        output = self.root / 'dist/ShokoAnalytics'
        output.mkdir(parents=True)
        (output / 'old.txt').write_text('previous')
        original_rename = Path.rename
        def rename(path, destination):
            if path == self.candidate:
                raise PermissionError('simulated file lock')
            return original_rename(path, destination)
        with patch.object(Path, 'rename', rename), self.assertRaises(PermissionError):
            package.publish(argparse.Namespace(candidate=self.candidate))
        self.assertEqual((output / 'old.txt').read_text(), 'previous')
        self.assertTrue((self.candidate / 'app/main.py').exists())

    def test_archive_failure_does_not_replace_previous_distribution(self):
        output = self.root / 'dist/ShokoAnalytics'
        output.mkdir(parents=True)
        (output / 'old.txt').write_text('previous')
        with patch.object(package, 'ZipFile', side_effect=OSError('simulated disk failure')), self.assertRaises(OSError):
            package.publish(argparse.Namespace(candidate=self.candidate))
        self.assertEqual((output / 'old.txt').read_text(), 'previous')
        self.assertTrue(self.candidate.exists())

    def test_successful_publication_has_verified_zip_and_preserves_old_folder(self):
        output = self.root / 'dist/ShokoAnalytics'
        output.mkdir(parents=True)
        (output / 'old.txt').write_text('previous')
        cache = self.candidate / 'app/__pycache__/generated.pyc'
        cache.parent.mkdir()
        cache.write_bytes(b'generated by test subprocess')
        package.publish(argparse.Namespace(candidate=self.candidate))
        self.assertEqual(package.verify(output)['version'], '0.1.0')
        self.assertFalse(cache.exists())
        previous = list((self.root / 'build').glob('previous-distribution-*'))
        self.assertEqual(len(previous), 1)
        self.assertEqual((previous[0] / 'old.txt').read_text(), 'previous')
        archive = self.root / 'dist/ShokoAnalytics-0.1.0-Windows.zip'
        with ZipFile(archive) as zipped:
            self.assertIsNone(zipped.testzip())
            self.assertEqual(zipped.read('ShokoAnalytics/app/main.py'), b'synthetic app/main.py')
        result = json.loads((self.root / 'runtime/portable-build/build-result.json').read_text())
        self.assertEqual(result['zip_sha256'], package.checksum(archive))
